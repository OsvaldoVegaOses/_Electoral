"""Explicit pilot capability. Deployment attestations are operational evidence, not external audits."""
import hashlib
import json
import re
from datetime import datetime, timezone
from pathlib import Path
from urllib.parse import urlsplit
from fastapi import HTTPException
from app.config import settings

COMMIT="337887bd1862c7cd057080b530fd80941bfc3c69"

def enabled(election=None):
    if settings.BELENIOS_MODE == "laboratory":
        return settings.ENVIRONMENT == "development"
    if settings.BELENIOS_MODE != "pilot" or settings.ENVIRONMENT not in ("production","staging"):
        return False
    schools={value.strip() for value in settings.BELENIOS_APPROVED_SCHOOLS.split(',') if value.strip().isdigit()}
    return bool(settings.BELENIOS_PILOT_APPROVAL.strip() and schools
                and (election is None or str(election.school_id) in schools))

def require_enabled(election=None):
    if not enabled(election):
        raise HTTPException(503,"Integración Belenios deshabilitada para este entorno/institución.")

def https_destination(value):
    parsed=urlsplit(value)
    allowed={host.strip().lower() for host in settings.BELENIOS_ALLOWED_HOSTS.split(',') if host.strip()}
    if (parsed.scheme != 'https' or not parsed.hostname or parsed.hostname.lower() not in allowed
            or parsed.port not in (None,443) or parsed.username or parsed.password or parsed.query or parsed.fragment
            or any(segment in ('.','..') for segment in parsed.path.split('/')) or '%' in parsed.path):
        raise HTTPException(503,"Destino HTTPS no autorizado en configuración.")
    return value.rstrip('/')

def alias_domain():
    if settings.BELENIOS_MODE == 'laboratory':
        return 'ejemplo.test'
    domain=settings.BELENIOS_ALIAS_DOMAIN.lower()
    if not re.fullmatch(r'[a-z0-9](?:[a-z0-9.-]*[a-z0-9])?\.[a-z]{2,63}',domain) or domain.endswith(('.test','.invalid','.localhost')):
        raise HTTPException(503,"Falta un dominio operativo de alias y su canal de autenticación.")
    return domain

def public_url(policy):
    if policy not in ('R1','R2'):
        raise HTTPException(503,"Política inválida")
    if settings.BELENIOS_MODE == 'laboratory':
        base=getattr(settings,f'BELENIOS_{policy}_URL').rstrip('/')
        return base if base == ('http://127.0.0.1:18001' if policy=='R1' else 'http://127.0.0.1:18002') else None
    return https_destination(getattr(settings,f'BELENIOS_{policy}_PUBLIC_URL'))

def confirm_manifest(policy,base):
    """Fail closed on modified/stale runtime evidence. Generated by a separate deployment operator."""
    try:
        data=Path(settings.BELENIOS_RUNTIME_MANIFEST).read_bytes()
        if hashlib.sha256(data).hexdigest() != settings.BELENIOS_RUNTIME_MANIFEST_SHA256:
            raise ValueError
        manifest=json.loads(data)
        expires=datetime.fromisoformat(manifest['valid_until'].replace('Z','+00:00'))
        observed=datetime.fromisoformat(manifest['observed_at'].replace('Z','+00:00'))
        now=datetime.now(timezone.utc)
        profile=manifest['profiles'][policy]
        if not (observed <= now < expires) or (expires-observed).total_seconds()>86400:
            raise ValueError
        if (manifest['approval_ref'] != settings.BELENIOS_PILOT_APPROVAL or profile['base_url'] != base
                or profile['upstream_commit'] != COMMIT or profile['deny_revote'] != (policy=='R2')
                or not re.fullmatch(r'sha256:[a-f0-9]{64}',profile['image_digest'])):
            raise ValueError
    except (OSError,ValueError,TypeError,KeyError):
        raise HTTPException(503,"Evidencia del runtime ausente, alterada, vencida o incompatible.") from None
